#!/usr/bin/env python3
"""Build 1-bit Newton Extras icons from a Kai glyph and a simple input field."""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = next(p for p in Path(__file__).resolve().parents if (p / 'source/main').is_dir())
FONT = Path("/System/Library/AssetsV2/com_apple_MobileAsset_Font8/88d6cc32a907955efa1d014207889413890573be.asset/AssetData/Kaiti.ttc")
SIZE = (26, 25)


def bitmap_hex(image: Image.Image) -> str:
    width, height = image.size
    # Newton monochrome bitmaps use a 16-byte header and 32-bit row alignment.
    header = bytes.fromhex("000000000004000000000000") + height.to_bytes(2, "big") + width.to_bytes(2, "big")
    rows = bytearray()
    for y in range(height):
        row = [0, 0, 0, 0]
        for x in range(width):
            if image.getpixel((x, y)):
                row[x // 8] |= 1 << (7 - x % 8)
        rows.extend(row)
    return (header + rows).hex().upper()


def icon_source(image: Image.Image, description: str, symbol: str) -> str:
    data = bitmap_hex(image)
    return (f"// Generated by source/main/UniBeijingX/tools/build_package_icons.py: {description}\n"
            f"DefGlobalVar('{symbol}, {{\n"
            f'    mask: MakeBinaryFromHex("{data}", \'mask),\n'
            f'    bits: MakeBinaryFromHex("{data}", \'bits),\n'
            "    bounds: {left: 0, top: 0, right: 26, bottom: 25},\n"
            "});\n")


def main() -> None:
    output = ROOT / "source" / "main" / "UniBeijingX" / "icons"
    output.mkdir(parents=True, exist_ok=True)

    source = output / "unibeijingx-26.png"
    if source.exists():
        font_icon = Image.open(source).convert("1")
        if font_icon.size != SIZE:
            raise SystemExit(f"Wrong icon dimensions: {source}")
    else:
        if not FONT.exists():
            raise SystemExit(f"Kai font unavailable: {FONT}")
        # Rasterize STKaiti only when authoring the source icon. Normal builds
        # use the committed 26x25 PNG and do not require that system font.
        glyph = Image.new("L", (64, 64), 0)
        draw = ImageDraw.Draw(glyph)
        draw.text((32, 32), "中", font=ImageFont.truetype(str(FONT), 28),
                  anchor="mm", fill=255)
        box = glyph.getbbox()
        if not box:
            raise SystemExit("STKaiti did not render 中")
        glyph = glyph.crop(box)
        glyph.thumbnail((23, 23), Image.Resampling.LANCZOS)
        font_icon = Image.new("1", SIZE, 0)
        glyph = glyph.point(lambda pixel: 255 if pixel >= 105 else 0).convert("1")
        font_icon.paste(glyph, ((26 - glyph.width) // 2, (25 - glyph.height) // 2))
        font_icon.save(source)

    input_icon = Image.new("1", SIZE, 0)
    draw = ImageDraw.Draw(input_icon)
    draw.rectangle((1, 5, 24, 19), outline=1, width=1)
    draw.line((5, 8, 5, 16), fill=1, width=1)
    draw.line((4, 8, 7, 8), fill=1, width=1)
    draw.line((4, 16, 7, 16), fill=1, width=1)
    input_icon.save(output / "pinyin-ime-26.png")

    for image, stem, path, description, symbol in (
        (font_icon, "unibeijingx", ROOT / "source/main/UniBeijingX/font-lite/Icon.newt", "STKaiti 中", "ubxFontIcon"),
        (input_icon, "pinyin-ime", ROOT / "source/main/PinyinIME/Icon.newt", "single input field", "ubxPinyinIcon"),
    ):
        image.resize((260, 250), Image.Resampling.NEAREST).save(output / f"{stem}.png")
        path.write_text(icon_source(image, description, symbol), encoding="utf-8")

    full = ROOT / "source/main/UniBeijingX/font-full/Icon.newt"
    full.write_text((ROOT / "source/main/UniBeijingX/font-lite/Icon.newt").read_text(), encoding="utf-8")


if __name__ == "__main__":
    main()
