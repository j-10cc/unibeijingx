#!/usr/bin/env python3
"""Generate a compact NewtonScript Pinyin dictionary from MIT-licensed data."""

from __future__ import annotations

import argparse
import json
import pathlib
import re
from collections import defaultdict

import jieba
from pypinyin import Style, lazy_pinyin, pinyin


ROOT = next(p for p in pathlib.Path(__file__).resolve().parents if (p / 'source/main').is_dir())
OUT = ROOT / "source/main/PinyinIME/Dictionary.newt"
MANIFEST = ROOT / "source/main/PinyinIME/dictionary-manifest.json"
PINYIN = re.compile(r"^[a-z]+$")
CORE_PHRASES = {
    "你好", "再见", "谢谢", "中国", "北京", "上海", "重庆",
    "中文", "拼音", "输入法", "今天", "明天", "朋友", "工作",
}


def gb2312_hanzi() -> set[str]:
    chars = set()
    for row in range(0xA1, 0xF8):
        for cell in range(0xA1, 0xFF):
            try:
                char = bytes((row, cell)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if "\u4e00" <= char <= "\u9fff":
                chars.add(char)
    return chars


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--phrase-limit", type=int, default=3000)
    args = parser.parse_args()

    hanzi = gb2312_hanzi()
    source = pathlib.Path(jieba.__file__).with_name("dict.txt")
    frequencies: dict[str, int] = {}
    phrases = []
    for line in source.open(encoding="utf-8"):
        fields = line.split()
        if len(fields) < 2:
            continue
        word, frequency = fields[0], int(fields[1])
        if len(word) == 1 and word in hanzi:
            frequencies[word] = frequency
        elif 2 <= len(word) <= 4 and all(char in hanzi for char in word):
            phrases.append((frequency, word))

    candidates: dict[str, dict[str, int]] = defaultdict(dict)
    covered = set()
    for char in sorted(hanzi):
        pronunciations = pinyin(char, style=Style.NORMAL, heteronym=True)[0]
        for reading in pronunciations:
            key = reading.lower()
            if PINYIN.fullmatch(key):
                candidates[key][char] = max(candidates[key].get(char, 0), frequencies.get(char, 1))
                covered.add(char)

    ranked_phrases = sorted(phrases, reverse=True)
    selected = ranked_phrases[: args.phrase_limit]
    selected.extend((frequency, word) for frequency, word in ranked_phrases
                    if word in CORE_PHRASES)
    included_phrases = set()
    for frequency, word in selected:
        key = "".join(lazy_pinyin(word, style=Style.NORMAL)).lower()
        if PINYIN.fullmatch(key):
            candidates[key][word] = max(candidates[key].get(word, 0), frequency)
            included_phrases.add(word)

    if covered != hanzi:
        raise ValueError(f"Missing Pinyin for {len(hanzi - covered)} GB2312 Hanzi")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as file:
        file.write("// Generated by source/main/PinyinIME/tools/build_pinyin_dict.py; source licenses in external/dictionaries.\n")
        file.write("DefGlobalVar('pinyinData, {\n")
        for key in sorted(candidates):
            ordered = sorted(candidates[key].items(), key=lambda pair: (-pair[1], len(pair[0]), pair[0]))
            words = [word for word, _ in ordered]
            file.write(f"    {key}: [\n")
            for offset in range(0, len(words), 8):
                group = words[offset : offset + 8]
                file.write("        " + ", ".join(json.dumps(word, ensure_ascii=False) for word in group))
                file.write(",\n" if offset + 8 < len(words) else "\n")
            file.write("    ],\n")
        file.write("});\n")

    manifest = {
        "encoding": "Unicode inside Newton; GB2312 defines repertoire",
        "gb2312_hanzi": len(hanzi),
        "hanzi_with_pinyin": len(covered),
        "phrases": len(included_phrases),
        "phrase_limit": args.phrase_limit,
        "keys": len(candidates),
        "candidates": sum(len(x) for x in candidates.values()),
        "source": ["jieba 0.42.1 dict.txt (MIT)", "pypinyin 0.55.0 (MIT)"],
    }
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False))


if __name__ == "__main__":
    main()
